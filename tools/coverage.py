"""Build the MITRE ATT&CK coverage report from the rules' mappings.

Writes:
  docs/coverage.md                    - table of tactics and techniques -> rules
  docs/attack-navigator-layer.json    - layer to open in ATT&CK Navigator

    python tools/coverage.py            # regenerate
    python tools/coverage.py --check    # CI: fail if the reports are stale
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import defaultdict

from rulelib import REPO_ROOT, TACTICS, load_rules

DOCS = REPO_ROOT / "docs"
MD_PATH = DOCS / "coverage.md"
LAYER_PATH = DOCS / "attack-navigator-layer.json"


def build() -> tuple[str, str]:
    rules = load_rules()
    by_technique: dict[str, list[str]] = defaultdict(list)
    # Rules declare tactics and techniques separately, so the tactic view lists
    # rules (always correct) rather than guessing which technique fits which tactic.
    by_tactic: dict[str, list[str]] = defaultdict(list)
    for rule in rules:
        for technique in rule.techniques:
            by_technique[technique].append(rule.name)
        for tactic in rule.tactics:
            by_tactic[tactic].append(rule.name)

    lines = [
        "# MITRE ATT&CK coverage",
        "",
        "Generated by `python tools/coverage.py` from the rule metadata. Do not edit by hand.",
        "",
        f"**{len(rules)} rules** cover **{len(by_technique)} techniques** "
        f"across **{len(by_tactic)} of {len(TACTICS)} tactics**.",
        "",
        "## By tactic",
        "",
        "| Tactic | Rules |",
        "| :--- | :--- |",
    ]
    for tactic in TACTICS:  # keep the kill-chain order
        names = "<br>".join(sorted(by_tactic.get(tactic, []))) or "— *(gap)*"
        lines.append(f"| {tactic} | {names} |")
    lines += ["", "## By technique", "", "| Technique | Rules |", "| :--- | :--- |"]
    for technique in sorted(by_technique):
        url = "https://attack.mitre.org/techniques/" + technique.replace(".", "/") + "/"
        lines.append(f"| [{technique}]({url}) | {'<br>'.join(sorted(by_technique[technique]))} |")
    markdown = "\n".join(lines) + "\n"

    layer = {
        "name": "sentinel-detection-lab coverage",
        "versions": {"layer": "4.5", "navigator": "5.1.0"},
        "domain": "enterprise-attack",
        "description": "Techniques with at least one rule in sentinel-detection-lab.",
        "techniques": [
            {
                "techniqueID": technique,
                "score": len(names),
                "comment": "; ".join(sorted(names)),
                "enabled": True,
            }
            for technique, names in sorted(by_technique.items())
        ],
        "gradient": {"colors": ["#c6dbef", "#08519c"], "minValue": 0, "maxValue": 3},
        "legendItems": [],
    }
    return markdown, json.dumps(layer, indent=2) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    markdown, layer = build()
    outputs = {MD_PATH: markdown, LAYER_PATH: layer}
    stale = [p for p, content in outputs.items()
             if not p.exists() or p.read_text(encoding="utf-8") != content]
    if args.check:
        for path in stale:
            print(f"STALE  {path.relative_to(REPO_ROOT).as_posix()} - run python tools/coverage.py")
        return 1 if stale else 0
    DOCS.mkdir(exist_ok=True)
    for path in stale:
        path.write_text(outputs[path], encoding="utf-8", newline="\n")
        print(f"WROTE  {path.relative_to(REPO_ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
